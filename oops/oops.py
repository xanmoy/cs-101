# encapsulation is the bundling of data and methods that operate on that data within a single unit, or class.
# It restricts direct access to some of the object's components and can prevent the accidental modification of data.
# encapsulation is a fundamental concept in object-oriented programming (OOP) that helps to protect the internal state of an object and control access to its data and methods.
# encapsulation is achieved by using access modifiers (private, protected, public) to restrict access to class members.
# encapsulation is a key principle of OOP that promotes data hiding and abstraction.
# encapsulation allows for better organization of code and makes it easier to maintain and understand.


